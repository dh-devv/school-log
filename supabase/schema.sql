create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.school_items (
  id bigint generated by default as identity primary key,
  title varchar(200) not null check (char_length(trim(title)) between 1 and 200),
  category text not null check (category in ('exam', 'holiday', 'school-anniversary', 'school-event', 'notice', 'other')),
  start_date date not null,
  end_date date,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_items_date_order check (end_date is null or end_date >= start_date)
);

create index if not exists school_items_start_date_idx on public.school_items (start_date);
create index if not exists school_items_category_idx on public.school_items (category);

create or replace function public.set_updated_at()
returns trigger language plpgsql security invoker as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists school_items_set_updated_at on public.school_items;
create trigger school_items_set_updated_at before update on public.school_items
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id) values (new.id) on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.school_items enable row level security;

drop policy if exists "profiles_read_own" on public.profiles;
create policy "profiles_read_own" on public.profiles for select to authenticated using (id = auth.uid());

drop policy if exists "public_can_read_school_items" on public.school_items;
create policy "public_can_read_school_items" on public.school_items for select to anon, authenticated using (true);

drop policy if exists "admins_can_insert_school_items" on public.school_items;
create policy "admins_can_insert_school_items" on public.school_items for insert to authenticated with check (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'));

drop policy if exists "admins_can_update_school_items" on public.school_items;
create policy "admins_can_update_school_items" on public.school_items for update to authenticated using (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin')) with check (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'));

drop policy if exists "admins_can_delete_school_items" on public.school_items;
create policy "admins_can_delete_school_items" on public.school_items for delete to authenticated using (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'));

